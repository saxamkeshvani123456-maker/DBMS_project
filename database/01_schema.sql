-- Run as CAMPUSCONNECT schema owner in Oracle 19c+.
-- IDs use identity columns consistently. FKs default to NO ACTION to preserve business history.
CREATE TABLE USERS (
 user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR2(120) NOT NULL, email VARCHAR2(254) NOT NULL UNIQUE,
 password_hash VARCHAR2(100) NOT NULL, enrollment_number VARCHAR2(32) UNIQUE,
 department VARCHAR2(100), year_of_study NUMBER(1), role VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT ck_user_role CHECK(role IN ('STUDENT','COORDINATOR','ADMIN')),
 CONSTRAINT ck_user_year CHECK(year_of_study IS NULL OR year_of_study BETWEEN 1 AND 6),
 CONSTRAINT ck_user_name CHECK(LENGTH(TRIM(full_name))>0)
);
CREATE TABLE CLUBS (
 club_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, club_name VARCHAR2(120) NOT NULL UNIQUE,
 description VARCHAR2(2000), category VARCHAR2(60), logo_url VARCHAR2(1000),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE CLUB_MEMBERSHIPS (
 membership_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id NUMBER NOT NULL REFERENCES USERS(user_id), club_id NUMBER NOT NULL REFERENCES CLUBS(club_id),
 membership_role VARCHAR2(20) DEFAULT 'MEMBER' NOT NULL, membership_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
 joined_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_membership UNIQUE(user_id,club_id),
 CONSTRAINT ck_membership_role CHECK(membership_role IN ('MEMBER','COORDINATOR')),
 CONSTRAINT ck_membership_status CHECK(membership_status IN ('PENDING','ACTIVE','LEFT'))
);
CREATE TABLE CLUB_REQUESTS (
 request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requested_by NUMBER NOT NULL REFERENCES USERS(user_id), proposed_name VARCHAR2(120) NOT NULL,
 description VARCHAR2(2000), status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
 reviewed_by NUMBER REFERENCES USERS(user_id), requested_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 reviewed_at TIMESTAMP WITH TIME ZONE,
 CONSTRAINT ck_request_status CHECK(status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE EVENTS (
 event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, club_id NUMBER NOT NULL REFERENCES CLUBS(club_id),
 created_by NUMBER NOT NULL REFERENCES USERS(user_id), title VARCHAR2(180) NOT NULL, description VARCHAR2(4000),
 venue VARCHAR2(180) NOT NULL, start_datetime TIMESTAMP WITH TIME ZONE NOT NULL, end_datetime TIMESTAMP WITH TIME ZONE NOT NULL,
 capacity NUMBER(7) NOT NULL, event_status VARCHAR2(20) DEFAULT 'PUBLISHED' NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT ck_event_dates CHECK(end_datetime>start_datetime), CONSTRAINT ck_event_capacity CHECK(capacity>0),
 CONSTRAINT ck_event_status CHECK(event_status IN ('DRAFT','PUBLISHED','CANCELLED','COMPLETED'))
);
CREATE TABLE EVENT_REGISTRATIONS (
 registration_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id NUMBER NOT NULL REFERENCES EVENTS(event_id), user_id NUMBER NOT NULL REFERENCES USERS(user_id),
 registration_status VARCHAR2(20) DEFAULT 'REGISTERED' NOT NULL,
 registered_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_event_user UNIQUE(event_id,user_id),
 CONSTRAINT ck_reg_status CHECK(registration_status IN ('REGISTERED','CANCELLED','ATTENDED'))
);
CREATE TABLE ANNOUNCEMENTS (
 announcement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_by NUMBER NOT NULL REFERENCES USERS(user_id), club_id NUMBER REFERENCES CLUBS(club_id),
 title VARCHAR2(180) NOT NULL, content CLOB NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE LOST_FOUND_ITEMS (
 item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reported_by NUMBER NOT NULL REFERENCES USERS(user_id),
 item_name VARCHAR2(160) NOT NULL, description VARCHAR2(2000), item_type VARCHAR2(10) NOT NULL,
 location VARCHAR2(180) NOT NULL, date_reported TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 item_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL, resolved_at TIMESTAMP WITH TIME ZONE,
 CONSTRAINT ck_item_type CHECK(item_type IN ('LOST','FOUND')),
 CONSTRAINT ck_item_status CHECK(item_status IN ('OPEN','CLAIMED','RESOLVED'))
);
CREATE TABLE ACADEMIC_RESOURCES (
 resource_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 uploaded_by NUMBER NOT NULL REFERENCES USERS(user_id), title VARCHAR2(180) NOT NULL,
 description VARCHAR2(2000), subject VARCHAR2(120) NOT NULL, semester NUMBER(2),
 resource_url VARCHAR2(1500) NOT NULL, uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT ck_resource_semester CHECK(semester IS NULL OR semester BETWEEN 1 AND 12)
);
CREATE TABLE APPLICATION_AUDIT_LOG (
 audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_name VARCHAR2(30) NOT NULL,
 record_id NUMBER NOT NULL, operation_type VARCHAR2(10) NOT NULL, changed_by VARCHAR2(128) NOT NULL,
 changed_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, old_values CLOB, new_values CLOB,
 CONSTRAINT ck_audit_operation CHECK(operation_type IN ('INSERT','UPDATE','DELETE'))
);
CREATE TABLE ACTIVITY_LOGS (
 log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id NUMBER REFERENCES USERS(user_id),
 action VARCHAR2(120) NOT NULL, entity_type VARCHAR2(50), entity_id NUMBER,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
COMMIT;
