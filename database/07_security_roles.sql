-- Execute once as an authorized DBA after the schema objects exist. Replace passwords out of band.
-- DB principals are separate from application USERS rows. Do not place real passwords in source control.
CREATE ROLE campus_read_role;
GRANT SELECT ON CAMPUSCONNECT.CLUBS TO campus_read_role;
GRANT SELECT ON CAMPUSCONNECT.V_EVENT_SUMMARY TO campus_read_role;
CREATE USER campus_guest IDENTIFIED BY "CcSchema2026";
GRANT CREATE SESSION TO campus_guest;
GRANT campus_read_role TO campus_guest;

